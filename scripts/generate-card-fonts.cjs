// One-off generator for lib/cards/poppins-data.ts: embeds the four Poppins weights
// (SIL Open Font License) the ID card uses as base64, so the PDF renderer needs no
// file access at runtime (files under /public are not reliably bundled into Vercel
// serverless functions). Run after `npm install --no-save @expo-google-fonts/poppins`.
const fs = require('fs')
const dir = 'node_modules/@expo-google-fonts/poppins'
const faces = { REGULAR: '400Regular/Poppins_400Regular.ttf', MEDIUM: '500Medium/Poppins_500Medium.ttf', SEMIBOLD: '600SemiBold/Poppins_600SemiBold.ttf', BOLD: '700Bold/Poppins_700Bold.ttf' }
let out = '// GENERATED by scripts/generate-card-fonts.cjs — Poppins (SIL Open Font License 1.1).\n// Do not edit by hand.\n\n'
for (const [name, file] of Object.entries(faces)) out += `export const POPPINS_${name}_BASE64 =\n  '${fs.readFileSync(`${dir}/${file}`).toString('base64')}'\n\n`
fs.writeFileSync('lib/cards/poppins-data.ts', out)
console.log('wrote lib/cards/poppins-data.ts', Math.round(out.length / 1024) + ' KB')
